/**
 * 의사 난수 생성 함수
 *
 * sin 함수를 사용한 간단한 의사 난수 생성 알고리즘입니다.
 * 같은 시드 값에 대해 항상 같은 난수를 반환하므로 결정적(deterministic) 난수가 필요할 때 유용합니다.
 *
 * 알고리즘 설명:
 * - 12.9898: sin 함수의 주기를 조절하는 상수로, 소수점을 사용하여 더 나은 분포를 생성합니다.
 * - 43758.5453: 결과를 스케일링하는 큰 상수로, 소수 부분을 추출하기 전에 값을 확대하여 더 균등한 분포를 만듭니다.
 * - Math.floor(value)를 빼서 소수 부분만 추출하여 0과 1 사이의 값을 반환합니다.
 *
 * 참고: 이 알고리즘은 간단한 해시 함수처럼 작동하며, 고품질 난수가 필요한 경우에는 더 정교한 알고리즘을 고려해야 합니다.
 *
 * @param seed - 랜덤 시드 값
 * @returns 0과 1 사이의 의사 난수 (0 <= return < 1)
 */
export const pseudoRandom = (seed: number) => {
  const value = Math.sin(seed * 12.9898) * 43758.5453;
  return value - Math.floor(value);
};
